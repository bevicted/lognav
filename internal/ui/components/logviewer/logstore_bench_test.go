// BenchmarkStore_Resident1M measures the resident heap of a fully loaded
// 1 M-row LogStore after a GC cycle.  Run with -benchtime 1x (one
// iteration) since the metric is a point-in-time heap snapshot, not a
// throughput rate.  The benchmark is the §6 gate: if HeapInuse after
// loading 1 M rows stays RAM-bounded (< a few hundred MB) we keep the
// all-in-memory design; if it exceeds the process limit we open a
// paged-store spec.  NOTE: the FINAL gate decision is made against a
// REAL collected >50 k archive; these synthetic numbers establish the
// baseline shape.
func BenchmarkStore_Resident1M(b *testing.B) {
	b.ReportAllocs()
	// Build the 1 M log corpus once; it is immutable input reused across
	// iterations (with -benchtime 1x there is only one).
	logs := newBenchLogs(b, 1_000_000)
	b.ResetTimer()
	for b.Loop() {
		// NewLogStore with depstest.NewTest(b) yields state.New() zero values
		// (JQ="", Search="", no Filters), so SetLogsRaw hits ApplyJQ's
		// empty-query early-return and DoSearch's nil-poster guard without ever
		// calling poster.Go — nil poster is safe.
		s := NewLogStore(depstest.NewTest(b), nil, "bench-1m")
		s.SetLogsRaw(logs)
		// Force a full GC so HeapInuse reflects live objects only, not
		// allocations that the mutator has already unreachable-d.
		runtime.GC()
		var ms runtime.MemStats
		runtime.ReadMemStats(&ms)
		b.ReportMetric(float64(ms.HeapInuse)/(1024*1024), "resident_MB")
		runtime.KeepAlive(s)
		if err := s.Close(); err != nil {
			b.Logf("BenchmarkStore_Resident1M: Close: %v", err)
		}
	}
}

// BenchmarkStore_Search1M measures the full search dispatch + compute at
// 1 M rows.  fakePoster runs chunk workers inline (synchronously) so
// DoSearch() returns only after every chunk has finished.  The loaded
// corpus is rebuilt per iteration (StopTimer) to avoid cumulative state
// across b.N runs; at -benchtime 1x this adds no overhead.
//
//nolint:dupl // structurally similar to BenchmarkStore_JQApply1M but exercises the search path (DoSearch/HandleSearchChunk) with different state mutations (SetSearch vs SetJQ) and different chunk types
func BenchmarkStore_Search1M(b *testing.B) {
	b.ReportAllocs()
	// Build the corpus once; immutable, shared across iterations.
	logs := newBenchLogs(b, 1_000_000)
	// "event" is a word present in every log line generated by
	// randomBenchPayload ("event %d at offset %d") so it reliably matches
	// across the full corpus and exercises all search-chunk workers.
	const searchTerm = "event"
	b.ResetTimer()
	for b.Loop() {
		// Rebuild a fresh store each iteration so result maps do not carry
		// forward stale entries from prior iterations.
		b.StopTimer()
		bundle := depstest.NewTest(b)
		s := NewLogStore(bundle, nil, "bench-search-1m")
		fp := &fakePoster{}
		s.SetPoster(fp)
		s.SetLogsRaw(logs)
		// Clear any chunks posted by SetLogsRaw's jq/filter passes (its DoSearch
		// runs with an empty query; wipe so the drain below is clean).
		fp.mu.Lock()
		fp.posted = fp.posted[:0]
		fp.mu.Unlock()
		bundle.State.SetSearch(searchTerm)
		b.StartTimer()

		// fakePoster.Go runs inline → DoSearch executes all chunk workers
		// synchronously before returning.  Drain chunks to apply results.
		s.DoSearch()
		for _, chunk := range fp.searchChunks() {
			s.HandleSearchChunk(chunk)
		}

		b.StopTimer()
		if err := s.Close(); err != nil {
			b.Logf("BenchmarkStore_Search1M: Close: %v", err)
		}
		b.StartTimer()
	}
}

// BenchmarkStore_FilterApply1M measures ApplyFilters over 1 M rows.
// ApplyFilters is synchronous (no poster involvement), so the timing is
// the raw hide-decision compute for the full corpus.  A term-Include rule
// is used (Aho-Corasick path, the common case).
func BenchmarkStore_FilterApply1M(b *testing.B) {
	b.ReportAllocs()
	logs := newBenchLogs(b, 1_000_000)
	// Include rule: keep only logs containing "error".  ~10% of lines will
	// be visible (those with severity Warning+ or whose msg happens to
	// include the word); the rest are hidden.  The exact hit rate does not
	// affect the benchmark — every log is evaluated.
	rules := []filter.Rule{{Type: filter.Include, Value: "error"}}
	b.ResetTimer()
	for b.Loop() {
		b.StopTimer()
		bundle := depstest.NewTest(b)
		s := NewLogStore(bundle, nil, "bench-filter-1m")
		s.SetPoster(&fakePoster{})
		s.SetLogsRaw(logs)
		bundle.State.SetFilters(rules)
		b.StartTimer()

		// ApplyFilters is synchronous; no chunks to drain.
		s.ApplyFilters()

		b.StopTimer()
		if err := s.Close(); err != nil {
			b.Logf("BenchmarkStore_FilterApply1M: Close: %v", err)
		}
		b.StartTimer()
	}
}

