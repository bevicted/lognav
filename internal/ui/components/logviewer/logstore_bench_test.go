// BenchmarkStore_StreamIngestOnLoop1M measures the ON-LOOP ingest cost of a
// 1 M-row stream with jq, filter rules and search all active: everything
// HandleLogStreamMsg → dispatchPendingBatches → spawn* (and the
// HandleJQChunk-sequenced filter/re-search) does on the loop goroutine before a
// chunk reaches a worker.  dropPoster discards the worker bodies, so the number
// is the loop's share of ingest alone — the quantity per-epoch compile caching
// targets (ticket 06 / audit item 12).  The jq worker's reply is synthesized so
// the measurement is not swamped by a million gojq evaluations.
func BenchmarkStore_StreamIngestOnLoop1M(b *testing.B) {
	b.ReportAllocs()
	const (
		rows  = 1_000_000
		batch = 2000
	)
	// One shared, immutable data map per row: entry data is never mutated in
	// place and the dropped workers never read it concurrently.
	data := map[string]any{"msg": "event happened"}
	logs := make([]icl.Log, batch)
	for i := range logs {
		logs[i] = icl.Log{Data: data, Metadata: icl.Metadata{TSMicro: int64(i)}}
	}
	results := make([]any, batch)
	for i := range results {
		results[i] = "event happened"
	}
	rules := []filter.Rule{
		{Type: filter.Include, Value: "event"},
		{Type: filter.HasField, Value: ".msg"},
	}
	b.ResetTimer()
	for b.Loop() {
		b.StopTimer()
		bundle := depstest.NewTest(b)
		bundle.State.SetJQ(".msg")
		bundle.State.SetSearch("event")
		bundle.State.SetFilters(rules)
		s := NewLogStore(bundle, nil, "bench-ingest-1m")
		s.SetPoster(dropPoster{})
		s.StartStream(rows)
		b.StartTimer()

		for k := range rows / batch {
			s.HandleLogStreamMsg(&msgs.LogStreamMsg{ID: s.GetQueryID(), Logs: logs})
			s.HandleJQChunk(JQChunkMsg{Instance: "bench-ingest-1m", ID: s.GetQueryID(), Offset: k, Results: results})
		}
		s.HandleLogStreamDoneMsg(&msgs.LogStreamDoneMsg{ID: s.GetQueryID()})

		b.StopTimer()
		if err := s.Close(); err != nil {
			b.Logf("BenchmarkStore_StreamIngestOnLoop1M: Close: %v", err)
		}
		b.StartTimer()
	}
}
